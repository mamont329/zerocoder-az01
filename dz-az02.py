import pandas as pd

# 1. Создаём DataFrame: 10 учеников, оценки по 5 предметам.
data = {
    'Ученик':       ['Аня', 'Боб', 'Вера', 'Гена', 'Даша', 'Егор', 'Женя', 'Зина', 'Игорь', 'Катя'],
    'Математика':   [5, 3, 4, 2, 5, 4, 3, 5, 4, 2],
    'Русский':      [4, 4, 5, 3, 5, 3, 4, 5, 3, 4],
    'Физика':       [3, 5, 4, 2, 4, 5, 3, 4, 5, 3],
    'История':      [5, 2, 3, 4, 5, 3, 4, 4, 2, 5],
    'Биология':     [4, 3, 5, 3, 4, 4, 5, 3, 4, 5],
}
df = pd.DataFrame(data)

# Выведите первые несколько строк DataFrame, чтобы убедиться, что данные загружены правильно
print("df.head()")
print(df.head())

# print('==========================')
# print("df")
# print(df)

# 2. Статистика по оценкам.
subjects = ['Математика', 'Русский', 'Физика', 'История', 'Биология']

print('==========================')
print('Средняя оценка по каждому предмету:')
print(df[subjects].mean())

print('==========================')
print('Медианная оценка по каждому предмету:')
print(df[subjects].median())

print('==========================')
Q1_math = df['Математика'].quantile(0.25)
Q3_math = df['Математика'].quantile(0.75)
print(f'Q1 по математике (25-й перцентиль): {Q1_math}')
print(f'Q3 по математике (75-й перцентиль): {Q3_math}')

# IQR — межквартильный размах
IQR = Q3_math - Q1_math
print(f'IQR по математике (Q3 - Q1): {IQR}')

print('==========================')
print('Стандартное отклонение по каждому предмету:')
print(df[subjects].std())
